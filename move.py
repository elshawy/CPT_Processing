# 첫 번째와 두 번째 밑줄 사이의 문자열(숫자)을 찾는 정규 표현식
# 패턴: '문자열_숫자_문자열.확장자'에서 '숫자' 부분만 캡처
REGEX_PATTERN = r'^[^_]*_(\d+)_.*$'

def move_files_by_number():
    """지정된 숫자 목록을 포함하는 파일을 대상 폴더로 이동합니다."""

    # 1. 대상 폴더 생성
    os.makedirs(TARGET_DIR, exist_ok=True)
    print(f"✅ 대상 폴더 준비 완료: {TARGET_DIR}\n")

    moved_count = 0
    
    # 2. 현재 디렉토리의 모든 파일 목록을 가져옵니다.
    for filename in os.listdir(SOURCE_DIR):
        full_path = os.path.join(SOURCE_DIR, filename)
        
        # 디렉토리가 아닌 파일만 처리
        if os.path.isfile(full_path) and filename != os.path.basename(__file__):
            
            # 정규 표현식을 사용하여 첫 번째와 두 번째 밑줄 사이의 숫자 추출 시도
            match = re.search(REGEX_PATTERN, filename)
            
            if match:
                # 첫 번째 캡처 그룹(괄호 안의 \d+)이 추출한 숫자입니다.
                extracted_number = match.group(1)
                
                # 추출된 숫자가 TARGET_NUMBERS 목록에 있는지 확인
                if extracted_number in TARGET_NUMBERS:
                    try:
                        # 파일 이동 실행
                        shutil.move(full_path, TARGET_DIR)
                        print(f"➡️ 이동 성공: {filename}")
                        moved_count += 1
                    except Exception as e:
                        print(f"❌ 이동 실패 ({filename}): {e}")
            
    print(f"\n======================================")
    print(f"✨ 작업 완료: 총 {moved_count}개의 파일이 이동되었습니다.")
    print(f"======================================")

if __name__ == "__main__":
    move_files_by_number()